import AppKit

public final class ClipboardMonitor {
    public var onChange: ((String) -> Void)?

    private let pasteboard: NSPasteboard
    private let interval: TimeInterval
    private var timer: Timer?
    private var lastChangeCount: Int

    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    public init(pasteboard: NSPasteboard = .general, interval: TimeInterval = 0.3) {
        self.pasteboard = pasteboard
        self.interval = interval
        self.lastChangeCount = pasteboard.changeCount
    }

    public func start() {
        lastChangeCount = pasteboard.changeCount
        timer?.invalidate()
        let timer = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            self?.poll()
        }
        timer.tolerance = interval / 2
        self.timer = timer
        RunLoop.main.add(timer, forMode: .common)
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Plain text already on the pasteboard. Blank and concealed contents are omitted.
    public func existingPlainText() -> String? {
        guard !shouldIgnoreCurrentContents() else { return nil }
        return plainText()
    }

    /// Reads the pasteboard immediately. The running timer calls this on its own.
    public func checkForChanges() {
        poll()
    }

    /// Replaces the pasteboard and remembers the new change count so the write is not recorded again.
    public func write(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard !shouldIgnoreCurrentContents(), let text = plainText() else { return }
        onChange?(text)
    }

    private func plainText() -> String? {
        guard let text = pasteboard.string(forType: .string) else { return nil }
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        return text
    }

    private func shouldIgnoreCurrentContents() -> Bool {
        let types = Set(pasteboard.types ?? [])
        return !types.isDisjoint(with: Self.ignoredTypes)
    }
}
